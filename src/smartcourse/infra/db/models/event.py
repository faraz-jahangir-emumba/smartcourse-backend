"""The two tables that make background work survive a crash.

`OutboxEvent` is how an event reaches Kafka without ever disagreeing with
the database. `FailedEvent` is where work that could not be done is kept
instead of disappearing.

Part A lists "Failed Events / Workflow Issues" among the nine analytics
metrics (Core Functional Requirements section 5), so failures need somewhere
to live rather than only a log line that scrolls away. Both tables were
written as skeletons in Module 1 so the metric would have a source and the
schema would not have to change later.

See docs/SCHEMA.md section 8.
"""

from datetime import datetime
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Index,
    Integer,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from smartcourse.infra.db.base import Base, UUIDMixin


class OutboxEvent(UUIDMixin, Base):
    """An event waiting to be published to Kafka. FR-16, FR-17, FR-18.

    The problem it solves. Saving an enrollment and publishing
    `student.enrolled` touch two systems that share no transaction, so
    either can succeed alone:

        Postgres commits, Kafka send fails    Ali is enrolled and nobody
                                              was told - and the event does
                                              not exist to be retried
        Kafka send works, Postgres rolls back an event about an enrollment
                                              that never happened

    Reordering does not help; whichever goes second can still fail.

    So the event is written *here*, in the same transaction as the
    enrollment. Both rows commit or neither does, and there is no window
    between them because there is only one commit. A separate dispatcher
    then reads unpublished rows and sends them on.

    This is the fix Module 2 deliberately deferred. `POST /publish` writes
    no status precisely so Postgres and Temporal could not disagree - which
    narrowed that window rather than closing it, and said so at the time.

    What it does not give you: the dispatcher can send to Kafka and crash
    before marking the row published, so a message may arrive twice.
    At-least-once is the guarantee, and `id` is how a consumer copes with
    it - it travels in the envelope as `event_id`, and a consumer that
    remembers which ids it has handled can skip the repeat. FR-17.

    The id is generated by Python rather than by Postgres, which is why
    UUIDMixin exists: the event body contains its own id, so the id has to
    be known before the row is written.
    """

    __tablename__ = "outbox"

    # Where it goes. Stored rather than derived from event_type, so the
    # routing decision is made once - where the event is created, with the
    # rest of its context - rather than by a lookup table the dispatcher
    # has to keep in step.
    topic: Mapped[str] = mapped_column(String(200))

    # The Kafka message key, which decides the partition and therefore what
    # stays in order. Ordering only holds *within* a partition, so two
    # events that must not be reordered - `student.enrolled` and
    # `student.withdrew` for one course - have to share a key.
    #
    # Nullable because Kafka allows a null key. It should almost never be
    # one: a null key is spread across partitions at random, which silently
    # gives up ordering.
    partition_key: Mapped[str | None] = mapped_column(String(200))

    # Duplicated inside payload, and worth the duplication: it is the field
    # anyone querying this table filters on, and a column can be indexed
    # where a JSON path is awkward.
    event_type: Mapped[str] = mapped_column(String(100), index=True)

    # The whole envelope - event_id, event_type, occurred_at, version and
    # data - not just the data.
    #
    # The event is complete the moment it is created, so the dispatcher is
    # a pipe rather than a thing that assembles messages. It also means a
    # row sitting here for an hour still says what was true when it
    # happened, including its schema version, rather than whatever the code
    # would produce now.
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Null means "not sent yet". The dispatcher's entire query is this
    # column being null.
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # How many times sending has been tried. Not used to give up - a row
    # that cannot be sent because Kafka is down must keep waiting - but a
    # row with a high count and no published_at is a stuck event, and
    # without this it is invisible.
    attempts: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default="0"
    )

    __table_args__ = (
        # The dispatcher asks one question, several times a second: which
        # rows are unpublished, oldest first. A partial index covers only
        # the rows matching its condition, so this index holds only the
        # backlog - usually a handful of rows - rather than every event
        # ever published. Same idea as uq_enrollments_one_active.
        #
        # Without it, the query degrades as the table grows, and the table
        # only ever grows.
        Index(
            "ix_outbox_unpublished",
            "created_at",
            postgresql_where=text("published_at IS NULL"),
        ),
        CheckConstraint("attempts >= 0", name="ck_outbox_attempts_non_negative"),
    )

    def __repr__(self) -> str:
        state = "pending" if self.published_at is None else "published"
        return f"<OutboxEvent {self.event_type} {state}>"


# The three async mechanisms, each of which can fail in its own way.
FAILURE_SOURCES = ("kafka", "celery", "temporal")

FAILURE_STATUSES = ("pending", "retrying", "resolved", "abandoned")


class FailedEvent(UUIDMixin, Base):
    """Something that was supposed to happen in the background and did not."""

    __tablename__ = "failed_events"

    source: Mapped[str] = mapped_column(String(20), index=True)

    # The topic, task or workflow name - whatever identifies the specific piece
    # of work within its mechanism.
    source_name: Mapped[str] = mapped_column(String(200), index=True)

    # JSONB rather than Text because the three sources carry different shapes,
    # and jsonb can still be queried and indexed. Text would force every
    # question about the payload to be answered by reading it in Python.
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB)

    error: Mapped[str] = mapped_column(Text)

    retry_count: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default="0"
    )

    status: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default="pending", index=True
    )

    occurred_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    __table_args__ = (
        CheckConstraint(
            "source IN ('kafka', 'celery', 'temporal')",
            name="ck_failed_events_source_valid",
        ),
        CheckConstraint(
            "status IN ('pending', 'retrying', 'resolved', 'abandoned')",
            name="ck_failed_events_status_valid",
        ),
        CheckConstraint(
            "retry_count >= 0", name="ck_failed_events_retry_count_non_negative"
        ),
    )

    def __repr__(self) -> str:
        return f"<FailedEvent {self.source}:{self.source_name} {self.status}>"
